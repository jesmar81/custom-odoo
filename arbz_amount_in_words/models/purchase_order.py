from odoo import api, fields, models

#Display amount in words in Sale order
class PurchaseOrder(models.Model):

    _inherit = 'purchase.order'

    def _compute_amount2words(self):

        for rec in self:
            currency_name = rec.currency_id.name.upper()

            # M.N. = Moneda Nacional (National Currency)
            # M.E. = Moneda Extranjera (Foreign Currency)
            currency_type = 'M.N' if currency_name == 'MXN' else 'M.E.'

            # Split integer and decimal part
            amount_i, amount_d = divmod(rec.amount_total, 1)
            amount_d = round(amount_d, 2)
            amount_d = int(round(amount_d * 100, 2))

            words = rec.currency_id.with_context(lang=rec.partner_id.lang or 'es_ES').amount_to_text(amount_i).upper()

            rec.amount_words = '%(words)s %(amount_d)02d/100 %(currency_type)s' % {
                                'words': words,
                                'amount_d': amount_d,
                                'currency_type': currency_type,
                            }

    amount_words = fields.Char(string="Total amount in words: ", help=
                "Total amount in words is automatically generated by the system", compute='_compute_amount2words')
